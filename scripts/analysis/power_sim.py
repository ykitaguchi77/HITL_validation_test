"""Simulation-based power for the pre-specified primary analyses (analysis_plan v2).

H1 (primary): in proposal trials (n >= 1),
    log(duration_sec) ~ log2(n) + gaze + order + session + seed + (1|annotator) + (1|image)
    one-sided test of slope < 0.
H2 (co-primary, non-inferiority of quality): per structure, ASSD(n=128) - ASSD(manual)
    upper 95% CI bound < delta, image-paired via the crossed mixed model.

Design generated by scripts/prepare_experiment.py's rules (A annotators, S slots,
G images per slot -> G sessions of S). Effect-size assumptions (pilot: few-shot
app index.csv, median 132 s, IQR 91-220 s -> log-scale residual SD ~0.5):
    manual -> n=128 time ratio r (default 0.70), linear in log2(n) from n=1 (ratio 1)
    residual SD on log scale sigma (default 0.5), annotator SD 0.3, image SD 0.3

Run:  python scripts/analysis/power_sim.py --annotators 6 --sims 300
Writes outputs/analysis/power_sim.csv and prints a table.
"""
from __future__ import annotations

import argparse
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from study_design import design_params, slot_of, MANUAL  # noqa: E402

warnings.filterwarnings("ignore")


def simulate_design(p: dict, rng: np.random.Generator) -> pd.DataFrame:
    """One dataset skeleton: every (annotator, image) pair once with its slot."""
    S, G, A = p["n_slots"], p["group_size"], p["n_annotators"]
    rows = []
    for a in range(A):
        for g in range(S):
            slot = slot_of(a, g, p)
            n = 0 if slot == MANUAL else int(slot[1:])
            for i in range(G):
                rows.append({"annotator": a, "image": g * G + i, "n": n,
                             "seed": rng.integers(3) if n else -1,
                             "session": rng.integers(G), "order": rng.integers(S),
                             "gaze": rng.integers(2)})
    return pd.DataFrame(rows)


def fit_slope(df: pd.DataFrame):
    """Crossed random intercepts (annotator, image) via variance components; returns (beta, se)."""
    import statsmodels.formula.api as smf
    d = df[df.n > 0].copy()
    d["log2n"] = np.log2(d.n)
    d["one"] = 1
    m = smf.mixedlm("y ~ log2n + gaze + order + session + C(seed)", d, groups="one",
                    vc_formula={"annotator": "0 + C(annotator)", "image": "0 + C(image)"})
    r = m.fit(reml=True, method="lbfgs")
    return float(r.params["log2n"]), float(r.bse["log2n"])


def fit_contrast(df: pd.DataFrame, n_hi: int = 128):
    """ASSD difference (n_hi vs manual) with crossed random intercepts; returns (est, se)."""
    import statsmodels.formula.api as smf
    d = df[(df.n == 0) | (df.n == n_hi)].copy()
    d["prop"] = (d.n > 0).astype(int)
    d["one"] = 1
    m = smf.mixedlm("y ~ prop + gaze", d, groups="one",
                    vc_formula={"annotator": "0 + C(annotator)", "image": "0 + C(image)"})
    r = m.fit(reml=True, method="lbfgs")
    return float(r.params["prop"]), float(r.bse["prop"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--annotators", type=int, default=6)
    ap.add_argument("--sims", type=int, default=300)
    ap.add_argument("--ratio", type=float, nargs="+", default=[0.8, 0.7, 0.6],
                    help="time ratio manual->n=128 (H1 effect)")
    ap.add_argument("--sigma", type=float, nargs="+", default=[0.4, 0.5, 0.6], help="log-scale residual SD")
    ap.add_argument("--sd-annot", type=float, default=0.3)
    ap.add_argument("--sd-image", type=float, default=0.3)
    ap.add_argument("--assd-sd", type=float, default=1.0, help="residual SD of ASSD [px] (H2)")
    ap.add_argument("--assd-delta", type=float, default=1.0, help="non-inferiority margin [px] (H2)")
    ap.add_argument("--assd-true-diff", type=float, nargs="+", default=[0.0, 0.3, 0.5])
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    p = design_params(args.annotators)
    rng = np.random.default_rng(args.seed)
    from scipy.stats import norm
    z = norm.ppf(0.95)
    out = []
    print(f"design: A={p['n_annotators']} S={p['n_slots']} G={p['group_size']} "
          f"obs={p['n_annotators'] * p['n_study_images']} (per n: {p['n_annotators'] * p['group_size']})")
    for ratio in args.ratio:
        beta = np.log(ratio) / np.log2(128)
        for sigma in args.sigma:
            hits = 0
            for _ in range(args.sims):
                df = simulate_design(p, rng)
                ua = rng.normal(0, args.sd_annot, p["n_annotators"])
                vi = rng.normal(0, args.sd_image, p["n_study_images"])
                base = np.log(130.0)
                mu = base + np.where(df.n > 0, beta * np.log2(np.maximum(df.n, 1)), 0.0) + 0.1 * df.gaze
                df["y"] = mu + ua[df.annotator] + vi[df.image] + rng.normal(0, sigma, len(df))
                try:
                    b, se = fit_slope(df)
                    hits += (b / se) < -z
                except Exception:
                    pass
            out.append({"test": "H1_slope", "ratio_n128_vs_manual": ratio, "beta_per_doubling": round(beta, 4),
                        "sigma": sigma, "power": hits / args.sims})
            print(f"H1  ratio={ratio:.2f} sigma={sigma:.1f}  power={hits / args.sims:.3f}", flush=True)
    for true_diff in args.assd_true_diff:
        hits = 0
        for _ in range(args.sims):
            df = simulate_design(p, rng)
            ua = rng.normal(0, 0.3, p["n_annotators"])
            vi = rng.normal(0, 0.8, p["n_study_images"])
            df["y"] = 2.3 + true_diff * (df.n > 0) + ua[df.annotator] + vi[df.image] + rng.normal(0, args.assd_sd, len(df))
            try:
                est, se = fit_contrast(df)
                hits += (est + z * se) < args.assd_delta
            except Exception:
                pass
        out.append({"test": "H2_noninferiority_n128", "true_diff_px": true_diff, "delta_px": args.assd_delta,
                    "sigma": args.assd_sd, "power": hits / args.sims})
        print(f"H2  true diff={true_diff:.1f}px delta={args.assd_delta}px  power={hits / args.sims:.3f}", flush=True)
    od = ROOT / "outputs" / "analysis"
    od.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(out).to_csv(od / "power_sim.csv", index=False)
    print(f"Wrote {od / 'power_sim.csv'}")


if __name__ == "__main__":
    main()
