"""Central configuration for the HITL annotation webapp.

Paths to the external dataset live here. Experiment-specific data (conditions,
per-annotator sessions, practice) live in ``scripts/webapp/config/experiment.json``
(generated by ``scripts/prepare_experiment.py``). Model proposals are NOT
computed at runtime: every (study image, n, seed) proposal of the fixed n-shot
decoder-LoRA checkpoints is precomputed offline into
``outputs/proposals/proposals.json`` (Eyelid_few_shot_HITL/scripts/eval/
export_study_proposals.py) and served by lookup, so the app needs no GPU/torch
and manual vs proposal items have identical latency (no timing side channel).
"""
